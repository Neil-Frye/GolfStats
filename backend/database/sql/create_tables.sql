-- Function to get a user ID by their email address
CREATE OR REPLACE FUNCTION public.get_user_id_by_email(email_address text)
RETURNS uuid
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT id 
  FROM auth.users 
  WHERE email = email_address
$$;