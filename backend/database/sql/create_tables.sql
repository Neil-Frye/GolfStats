-- User preferences table
CREATE TABLE IF NOT EXISTS public.user_preferences (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) not null,
    preferred_units varchar(10) default 'yards',
    handicap varchar(10),
    home_course varchar(255),
    phone varchar(50),
    avatar_url varchar(255),
    trackman_username varchar(255),
    trackman_password varchar(255),
    arccos_email varchar(255),
    arccos_password varchar(255),
    skytrak_username varchar(255),
    skytrak_password varchar(255),
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now(),
    UNIQUE(user_id)
);
-- Add RLS policies
ALTER TABLE public.user_preferences ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own preferences" 
    ON public.user_preferences FOR SELECT 
    USING (auth.uid() = user_id);
CREATE POLICY "Users can insert their own preferences" 
    ON public.user_preferences FOR INSERT 
    WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can update their own preferences" 
    ON public.user_preferences FOR UPDATE 
    USING (auth.uid() = user_id);

