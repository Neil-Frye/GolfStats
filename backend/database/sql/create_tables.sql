-- Golf holes table
CREATE TABLE IF NOT EXISTS public.golf_holes (
    id bigint generated by default as identity primary key,
    round_id bigint references public.golf_rounds(id) on delete cascade not null,
    hole_number integer not null,
    par integer not null,
    score integer,
    fairway_hit boolean,
    green_in_regulation boolean,
    putts integer,
    distance_yards integer,
    notes text,
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now()
);
-- Add RLS policies 
ALTER TABLE public.golf_holes ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own holes through rounds" 
    ON public.golf_holes FOR SELECT 
    USING (EXISTS (
        SELECT 1 FROM public.golf_rounds
        WHERE public.golf_rounds.id = round_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));
CREATE POLICY "Users can insert holes to their own rounds" 
    ON public.golf_holes FOR INSERT 
    WITH CHECK (EXISTS (
        SELECT 1 FROM public.golf_rounds
        WHERE public.golf_rounds.id = round_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));
CREATE POLICY "Users can update holes of their own rounds" 
    ON public.golf_holes FOR UPDATE 
    USING (EXISTS (
        SELECT 1 FROM public.golf_rounds
        WHERE public.golf_rounds.id = round_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));
CREATE POLICY "Users can delete holes of their own rounds" 
    ON public.golf_holes FOR DELETE 
    USING (EXISTS (
        SELECT 1 FROM public.golf_rounds
        WHERE public.golf_rounds.id = round_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));

-- Golf shots table
CREATE TABLE IF NOT EXISTS public.golf_shots (
    id bigint generated by default as identity primary key,
    hole_id bigint references public.golf_holes(id) on delete cascade not null,
    shot_number integer not null,
    club varchar(50),
    distance_yards real,
    from_location varchar(50),
    to_location varchar(50),
    is_penalty boolean default false,
    ball_speed_mph real,
    club_speed_mph real,
    smash_factor real,
    launch_angle_degrees real,
    spin_rate_rpm real,
    spin_axis_degrees real,
    carry_distance_yards real,
    total_distance_yards real,
    side_deviation_yards real,
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now()
);
-- Add RLS policies (complex - linking through multiple tables)
ALTER TABLE public.golf_shots ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own shots through holes and rounds" 
    ON public.golf_shots FOR SELECT 
    USING (EXISTS (
        SELECT 1 FROM public.golf_holes
        JOIN public.golf_rounds ON public.golf_rounds.id = public.golf_holes.round_id
        WHERE public.golf_holes.id = hole_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));
CREATE POLICY "Users can insert shots to their own holes" 
    ON public.golf_shots FOR INSERT 
    WITH CHECK (EXISTS (
        SELECT 1 FROM public.golf_holes
        JOIN public.golf_rounds ON public.golf_rounds.id = public.golf_holes.round_id
        WHERE public.golf_holes.id = hole_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));
CREATE POLICY "Users can update shots in their own holes" 
    ON public.golf_shots FOR UPDATE 
    USING (EXISTS (
        SELECT 1 FROM public.golf_holes
        JOIN public.golf_rounds ON public.golf_rounds.id = public.golf_holes.round_id
        WHERE public.golf_holes.id = hole_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));
CREATE POLICY "Users can delete shots in their own holes" 
    ON public.golf_shots FOR DELETE 
    USING (EXISTS (
        SELECT 1 FROM public.golf_holes
        JOIN public.golf_rounds ON public.golf_rounds.id = public.golf_holes.round_id
        WHERE public.golf_holes.id = hole_id 
        AND public.golf_rounds.user_id = auth.uid()
    ));

